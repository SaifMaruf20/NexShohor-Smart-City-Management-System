-- Transport: Incidents ----------------------------------------
CREATE TABLE INCIDENTS (
    INCIDENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REPORTED_BY VARCHAR2(100) NOT NULL,
    AREA        VARCHAR2(100) NOT NULL,
    TITLE       VARCHAR2(200) NOT NULL,
    DESCRIPTION CLOB,
    SEVERITY    VARCHAR2(20)  DEFAULT 'Low'
                CHECK (SEVERITY IN ('Low', 'Medium', 'High', 'Critical')),
    STATUS      VARCHAR2(20)  DEFAULT 'Open'
                CHECK (STATUS IN ('Open', 'In Progress', 'Resolved')),
    CROWD_LEVEL VARCHAR2(20)
                CHECK (CROWD_LEVEL IN ('Low', 'Moderate', 'High', 'Jammed')),
    CREATED_AT  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_incident_user FOREIGN KEY (REPORTED_BY)
        REFERENCES nexshohor_users(email)
);
/

-- Transport: Crowd Reports ------------------------------------
CREATE TABLE CROWD_REPORTS (
    REPORT_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INCIDENT_ID NUMBER        NOT NULL,
    REPORTED_BY VARCHAR2(100) NOT NULL,
    CROWD_LEVEL VARCHAR2(20)
                CHECK (CROWD_LEVEL IN ('Low', 'Moderate', 'High', 'Jammed')),
    NOTE        VARCHAR2(500),
    REPORTED_AT TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_crowd_incident FOREIGN KEY (INCIDENT_ID) REFERENCES INCIDENTS(INCIDENT_ID)    ON DELETE CASCADE,
    CONSTRAINT fk_crowd_user     FOREIGN KEY (REPORTED_BY) REFERENCES nexshohor_users(email)
);
/

-- Emergency: Service Types ------------------------------------
CREATE TABLE SERVICE_TYPES (
    TYPE_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TYPE_NAME  VARCHAR2(50) NOT NULL UNIQUE,
    ICON       VARCHAR2(10),
    CREATED_AT TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);
/

-- Emergency: Services Directory -------------------------------
CREATE TABLE EMERGENCY_SERVICES (
    SERVICE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TYPE_ID    NUMBER        NOT NULL,
    NAME       VARCHAR2(200) NOT NULL,
    AREA       VARCHAR2(100) NOT NULL,
    ADDRESS    VARCHAR2(300),
    PHONE      VARCHAR2(20),
    IS_ACTIVE  NUMBER(1)     DEFAULT 1,
    CREATED_AT TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_es_type FOREIGN KEY (TYPE_ID)
        REFERENCES SERVICE_TYPES(TYPE_ID)
);
/

-- Emergency: SOS Logs -----------------------------------------
CREATE TABLE SOS_LOGS (
    SOS_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_EMAIL          VARCHAR2(100) NOT NULL,
    SERVICE_TYPE        VARCHAR2(50)  NOT NULL
                        CHECK (SERVICE_TYPE IN ('hospital', 'police', 'fire', 'ambulance', 'pharmacy')),
    AREA                VARCHAR2(100) NOT NULL,
    DESCRIPTION         CLOB,
    IS_RESOLVED         NUMBER(1)     DEFAULT 0,
    ASSIGNED_SERVICE_ID NUMBER,
    ADMIN_NOTE          VARCHAR2(500),
    CREATED_AT          TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    RESOLVED_AT         TIMESTAMP,
    CONSTRAINT fk_sos_user    FOREIGN KEY (USER_EMAIL)          REFERENCES nexshohor_users(email),
    CONSTRAINT fk_sos_service FOREIGN KEY (ASSIGNED_SERVICE_ID) REFERENCES EMERGENCY_SERVICES(SERVICE_ID)
);
/

-- Alerts: Areas -----------------------------------------------
CREATE TABLE UA_AREAS (
    AREA_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AREA_NAME  VARCHAR2(100) NOT NULL UNIQUE,
    IS_ACTIVE  NUMBER(1)     DEFAULT 1,
    CREATED_AT TIMESTAMP     DEFAULT CURRENT_TIMESTAMP
);
/

-- Alerts: Urban Alerts ----------------------------------------
CREATE TABLE URBAN_ALERTS (
    ALERT_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ISSUED_BY_ADMIN VARCHAR2(100) NOT NULL,
    AREA_ID         NUMBER        NOT NULL,
    ALERT_TYPE      VARCHAR2(30)
                    CHECK (ALERT_TYPE IN ('water_outage', 'roadblock', 'weather', 'strike', 'crime')),
    TITLE           VARCHAR2(200) NOT NULL,
    DESCRIPTION     CLOB,
    EXPIRES_AT      TIMESTAMP,
    IS_ACTIVE       NUMBER(1)     DEFAULT 1,
    CREATED_AT      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_alert_area FOREIGN KEY (AREA_ID)
        REFERENCES UA_AREAS(AREA_ID)
);
/

-- Alerts: Bookmarks -------------------------------------------
CREATE TABLE ALERT_BOOKMARKS (
    BOOKMARK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_EMAIL  VARCHAR2(100) NOT NULL,
    POST_ID     NUMBER,
    ALERT_ID    NUMBER,
    SAVED_AT    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_bookmark UNIQUE (USER_EMAIL, POST_ID, ALERT_ID),
    CONSTRAINT fk_bm_user  FOREIGN KEY (USER_EMAIL) REFERENCES nexshohor_users(email)   ON DELETE CASCADE,
    CONSTRAINT fk_bm_post  FOREIGN KEY (POST_ID)    REFERENCES HOUSE_POST(POST_ID)      ON DELETE CASCADE,
    CONSTRAINT fk_bm_alert FOREIGN KEY (ALERT_ID)   REFERENCES URBAN_ALERTS(ALERT_ID)   ON DELETE CASCADE
);
/


